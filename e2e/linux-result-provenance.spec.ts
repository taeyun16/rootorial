import { expect, test } from "@playwright/test";
const preview = process.env.CONTENT_PREVIEW_URL ?? "http://localhost:3101";
const url = (slug: string) => `${preview}/admin/preview/curricula/linux-systems/chapters/${slug}?lang=en`;
for (const width of [360, 390, 1440]) {
  test(`memory result keeps its submitted address and accumulated mastery after edits at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 });
    await page.goto(url("memory-and-virtual-addresses"));
    const lab = page.locator(".virtual-memory-lab");
    const prediction = lab.getByRole("group", { name: "Predict result", exact: true });
    const run = lab.getByRole("button", { name: "Run and evaluate CPU access" });
    for (const [preset, choice] of [["1. Shared read", "mapped"], ["2. COW write", "COW copy + resume"], ["3. Demand page", "demand-zero + resume"]]) {
      await lab.getByRole("button", { name: preset, exact: true }).click();
      await prediction.getByRole("button", { name: choice, exact: true }).click();
      await run.click();
      await expect(lab.locator(".memory-result-provenance")).toHaveAttribute("data-evidence", "current");
    }
    await expect(lab.locator(".memory-evidence .is-complete")).toHaveCount(5);
    const proof = lab.locator(".memory-result-provenance");
    await expect(proof).toContainText("VA 0x5018");
    await expect(lab.locator(".memory-translation-strip")).toContainText("0xd018");
    await lab.getByRole("textbox", { name: "Virtual address input" }).fill("0xffff");
    await expect(proof).toHaveAttribute("data-evidence", "stale");
    await expect(proof).toContainText("current inputs have not been run");
    await expect(proof).toContainText("VA 0x5018");
    await expect(proof).toContainText("VA 0xffff");
    await expect(lab.locator(".memory-evidence .is-complete")).toHaveCount(5);
    await expect(lab.locator(".memory-lab-mastered")).toBeVisible();
    await prediction.getByRole("button", { name: "unmapped → SIGSEGV", exact: true }).click();
    await run.click();
    await expect(proof).toHaveAttribute("data-evidence", "current");
    await expect(lab.locator(".memory-live-feedback")).toContainText("SIGSEGV");
    await expect(lab.locator(".memory-translation-strip")).toContainText("0xffff");
    await expect(lab.locator(".memory-translation-strip")).not.toContainText("0xd018");
    await expect(lab.locator(".memory-evidence .is-complete")).toHaveCount(5);
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
    await lab.getByRole("button", { name: "Reset lab", exact: true }).click();
    await expect(proof).toHaveCount(0);
    await expect(lab.locator(".memory-evidence .is-complete")).toHaveCount(0);
  });
  test(`storage trace labels previous namespace evidence and preserves causal mastery at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 844 });
    await page.goto(url("storage-and-filesystems"));
    const lab = page.locator(".storage-path-lab");
    await lab.getByRole("group", { name: "Predict filesystem", exact: true }).getByRole("button", { name: "datafs", exact: true }).click();
    for (const [label, value] of [["Predicted inode number", "17"], ["Predicted logical block", "1"], ["Predicted in-block offset", "0x340"], ["Predicted device block", "44"], ["Predicted device byte address", "0x2c340"]]) await lab.getByRole("textbox", { name: label, exact: true }).fill(value);
    const run = lab.getByRole("button", { name: "Run path and block trace" });
    await run.click();
    const proof = lab.locator(".storage-result-provenance");
    await expect(proof).toHaveAttribute("data-evidence", "current");
    await lab.getByRole("button", { name: "Create report.link" }).click();
    await lab.getByRole("button", { name: "Unlink original report.bin" }).click();
    await expect(proof).toHaveAttribute("data-evidence", "stale");
    await lab.getByRole("button", { name: "Write cache this round" }).click();
    await lab.getByRole("textbox", { name: "Predicted version marker after crash" }).fill("draft");
    await lab.getByRole("button", { name: "Crash this round and evaluate" }).click();
    await lab.getByRole("button", { name: "Write cache this round" }).click();
    await lab.getByRole("button", { name: "Second round: fsync file" }).click();
    await expect(lab.locator(".storage-feedback")).toContainText("fsync moved");
    await lab.getByRole("textbox", { name: "Storage path to trace" }).fill("/missing");
    await expect(proof).toContainText("current inputs and state have not been traced");
    await expect(proof).toContainText("Submitted inputs: /srv/data/report.bin");
    await expect(proof).toContainText("Current inputs: /missing");
    await expect(lab.locator(".storage-trace")).toContainText("0x2c340");
    await lab.getByRole("textbox", { name: "Predicted version marker after crash" }).fill("durable-v3");
    await lab.getByRole("button", { name: "Crash this round and evaluate" }).click();
    await expect(lab.locator(".storage-evidence .is-complete")).toHaveCount(5);
    await expect(lab.locator(".storage-lab-mastered")).toBeVisible();
    await run.click();
    await expect(proof).toHaveAttribute("data-evidence", "current");
    await expect(lab.locator(".storage-feedback")).toContainText("did not reach a file and block");
    await expect(lab.locator(".storage-trace")).not.toContainText("0x2c340");
    await expect(lab.locator(".storage-evidence .is-complete")).toHaveCount(5);
    await expect(lab.locator(".storage-lab-mastered")).toBeVisible();
    expect(await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)).toBeLessThanOrEqual(1);
    await lab.getByRole("button", { name: "Reset lab", exact: true }).click();
    await expect(proof).toHaveCount(0);
    await expect(lab.locator(".storage-evidence .is-complete")).toHaveCount(0);
  });
}
